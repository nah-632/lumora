"use client";

import { useEffect, useState } from "react";
import { AlertCard, type StudentAlert } from "./AlertCard";
import type { RosterStudent } from "./StudentRoster";

interface GradeRow {
  id: string;
  subject: string;
  assessment_name: string;
  score: number;
  max_score: number;
  date: string;
}

interface SubmissionRow {
  id: string;
  project_name: string;
  status: "submitted" | "late" | "missing";
  date: string;
}

interface InterventionRow {
  id: string;
  action: string;
  subject: string | null;
  occurred_on: string;
}

type Tab = "grades" | "submissions" | "interventions" | "timeline";

interface Props {
  locale: "ar" | "en";
  student: RosterStudent;
  onBack: () => void;
}

